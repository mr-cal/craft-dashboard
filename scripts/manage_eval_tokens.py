#!/usr/bin/env python3
"""CLI utility to create, list, and revoke evaluation API tokens."""

from __future__ import annotations

import asyncio
import hashlib
import pathlib
import secrets
import sys
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

import click
from rich.console import Console
from rich.table import Table

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from craft_dashboard.database import get_engine, get_session_factory
from craft_dashboard.repositories.eval_token_repository import EvalTokenRepository
from craft_dashboard.services.eval_auth_service import evict_eval_token
from craft_dashboard.settings import Settings

console = Console()


def _get_session_factory() -> async_sessionmaker[AsyncSession]:
    settings = Settings()
    engine = get_engine(
        settings.database_url,
        pool_size=settings.db_pool_size,
        max_overflow=settings.db_max_overflow,
    )
    return get_session_factory(engine)


@click.group()
def cli() -> None:
    """Manage evaluation tokens for workers and administrators."""


@cli.command(name="create")
@click.option(
    "--id",
    "token_id",
    required=True,
    help="Unique token identifier (e.g. stormclanker, mr-cal-bot)",
)
@click.option("--name", required=True, help="Human-readable description or owner name")
@click.option(
    "--admin",
    is_flag=True,
    default=False,
    help="Grant admin permissions (eval:admin) in addition to eval:write",
)
@click.option(
    "--token",
    "custom_token",
    default=None,
    help="Custom secret token string. If omitted, a secure 'cde_<hex>' token is generated.",
)
def create_token_cmd(
    token_id: str, name: str, admin: bool, custom_token: str | None
) -> None:
    """Create a new evaluation API token."""
    raw_token = custom_token or f"cde_{secrets.token_hex(24)}"
    token_hash = hashlib.sha256(raw_token.encode("utf-8")).hexdigest()
    token_prefix = f"{raw_token[:8]}..."
    permissions = ["eval:write", "eval:admin"] if admin else ["eval:write"]

    async def _create() -> None:
        session_factory = _get_session_factory()
        async with session_factory() as session:
            repo = EvalTokenRepository(session)
            existing = await repo.get_by_id(token_id)
            if existing:
                console.print(
                    f"[bold red]Error:[/] Token with ID '{token_id}' already exists."
                )
                sys.exit(1)

            await repo.create_token(
                token_id=token_id,
                name=name,
                token_hash=token_hash,
                token_prefix=token_prefix,
                permissions=permissions,
            )
            await session.commit()

        console.print(
            f"[bold green]Success:[/] Created evaluation token '[bold]{token_id}[/]'."
        )
        console.print(f"Name:        {name}")
        console.print(f"Prefix:      {token_prefix}")
        console.print(f"Permissions: {', '.join(permissions)}")
        console.print(f"[bold yellow]Secret Token:[/] {raw_token}")
        console.print(
            "[dim]Save this token now; it cannot be viewed again once lost.[/dim]"
        )

    asyncio.run(_create())


@cli.command(name="list")
@click.option(
    "--all", "include_all", is_flag=True, default=False, help="Include revoked tokens"
)
@click.option(
    "--stats",
    is_flag=True,
    default=False,
    help="Show evaluation counts generated by each token",
)
def list_tokens_cmd(include_all: bool, stats: bool) -> None:
    """List registered evaluation tokens."""

    async def _list() -> None:
        session_factory = _get_session_factory()
        async with session_factory() as session:
            repo = EvalTokenRepository(session)
            tokens = await repo.list_tokens(include_revoked=include_all)
            eval_counts = await repo.get_evaluation_counts_by_token() if stats else {}

        table = Table(title="Evaluation API Tokens")
        table.add_column("ID", style="cyan", no_wrap=True)
        table.add_column("Name", style="white")
        table.add_column("Prefix", style="dim")
        table.add_column("Permissions", style="magenta")
        table.add_column("Status", style="bold")
        table.add_column("Created", style="dim")
        table.add_column("Last Used", style="dim")
        if stats:
            table.add_column("Evaluations", justify="right", style="green")

        for token in tokens:
            status = "[green]active[/]" if token.is_active else "[red]revoked[/]"
            created_str = (
                token.created_at.strftime("%Y-%m-%d %H:%M") if token.created_at else "-"
            )
            used_str = (
                token.last_used_at.strftime("%Y-%m-%d %H:%M")
                if token.last_used_at
                else "never"
            )
            perms_str = ", ".join(token.permissions or [])
            row = [
                token.id,
                token.name,
                token.token_prefix,
                perms_str,
                status,
                created_str,
                used_str,
            ]
            if stats:
                count = eval_counts.get(token.id, 0)
                row.append(f"{count:,}")
            table.add_row(*row)

        console.print(table)

    asyncio.run(_list())


@cli.command(name="revoke")
@click.option("--id", "token_id", required=True, help="Token ID to revoke")
def revoke_token_cmd(token_id: str) -> None:
    """Revoke an evaluation token."""

    async def _revoke() -> None:
        session_factory = _get_session_factory()
        async with session_factory() as session:
            repo = EvalTokenRepository(session)
            revoked = await repo.revoke_token(token_id)
            if not revoked:
                console.print(
                    f"[bold red]Error:[/] Token '{token_id}' not found or already revoked."
                )
                sys.exit(1)
            await session.commit()
            evict_eval_token(token_id)

        console.print(
            f"[bold green]Revoked:[/] Token '[bold]{token_id}[/]' is now inactive and evicted from cache."
        )

    asyncio.run(_revoke())


if __name__ == "__main__":
    cli()
